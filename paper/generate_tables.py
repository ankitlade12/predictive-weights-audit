"""
Auto-generate LaTeX tables and figures from experiment results.

Reads JSON results from results/ and produces publication-ready
LaTeX tables that can be \input{} into main.tex.

Usage:
    python paper/generate_tables.py
"""

import json
import os
import sys
import glob

RESULTS_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "results")
OUTPUT_DIR = os.path.dirname(__file__)


def load_results(subdir, filename="results.json"):
    path = os.path.join(RESULTS_DIR, subdir, filename)
    if os.path.exists(path):
        with open(path) as f:
            return json.load(f)
    return None


def bold_best(values, higher_is_better=True):
    """Return list of formatted strings with best bolded."""
    if not values:
        return []
    nums = []
    for v in values:
        try:
            nums.append(float(v))
        except (ValueError, TypeError):
            nums.append(None)

    if higher_is_better:
        best = max(n for n in nums if n is not None)
    else:
        best = min(n for n in nums if n is not None)

    formatted = []
    for n in nums:
        if n is None:
            formatted.append("--")
        elif abs(n - best) < 1e-6:
            formatted.append(f"\\textbf{{{n:.3f}}}")
        else:
            formatted.append(f"{n:.3f}")
    return formatted


def generate_table1():
    """Table 1: Main synthetic benchmark (AUROC)."""
    # Try multiple result sources
    results = load_results("exp1_synthetic")
    if results is None:
        results = load_results("week3_benchmark")
    if results is None:
        print("  [SKIP] Table 1 — no results found")
        return

    methods = ["SSM-Causal", "Granger", "PCMCI", "cLSTM"]

    lines = []
    lines.append("% Auto-generated by generate_tables.py")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{AUROC on synthetic causal discovery benchmarks. "
                  "\\textbf{Bold} indicates best result.}")
    lines.append("\\label{tab:synthetic}")
    lines.append("\\begin{tabular}{l" + "c" * len(methods) + "}")
    lines.append("\\toprule")
    lines.append("Dataset & " + " & ".join(f"\\textbf{{{m}}}" for m in methods) + " \\\\")
    lines.append("\\midrule")

    for ds_name, ds_results in results.items():
        aurocs = [ds_results.get(m, {}).get("auroc") for m in methods]
        formatted = bold_best(aurocs)
        lines.append(f"{ds_name} & " + " & ".join(formatted) + " \\\\")

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")

    output_path = os.path.join(OUTPUT_DIR, "table1_synthetic.tex")
    with open(output_path, "w") as f:
        f.write("\n".join(lines))
    print(f"  Table 1 -> {output_path}")


def generate_table2():
    """Table 2: Non-stationary / regime-switching results."""
    results = load_results("exp2_nonstationary")
    if results is None:
        print("  [SKIP] Table 2 — no results found")
        return

    methods = list(results.keys())

    lines = []
    lines.append("% Auto-generated by generate_tables.py")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{AUROC on regime-switching VAR(1). "
                  "Causal structure reverses at $t=T/2$.}")
    lines.append("\\label{tab:nonstationary}")
    lines.append("\\begin{tabular}{lcccc}")
    lines.append("\\toprule")
    lines.append("Method & AUROC & F1 & Precision & Recall \\\\")
    lines.append("\\midrule")

    aurocs = [results[m].get("auroc") for m in methods]
    best_auroc = max(a for a in aurocs if a is not None)

    for method in methods:
        m = results[method]
        auroc = m.get("auroc", 0)
        f1 = m.get("f1", 0)
        prec = m.get("precision", 0)
        rec = m.get("recall", 0)

        auroc_str = f"\\textbf{{{auroc:.3f}}}" if abs(auroc - best_auroc) < 1e-6 else f"{auroc:.3f}"
        lines.append(f"{method} & {auroc_str} & {f1:.3f} & {prec:.3f} & {rec:.3f} \\\\")

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")

    output_path = os.path.join(OUTPUT_DIR, "table2_nonstationary.tex")
    with open(output_path, "w") as f:
        f.write("\n".join(lines))
    print(f"  Table 2 -> {output_path}")


