def generate_table4():
    """Table 4: Runtime/efficiency comparison."""
    results = load_results("exp5_efficiency", "efficiency_results.json")
    if results is None:
        print("  [SKIP] Table 4 — no efficiency results found")
        return

    methods = ["SSM-Causal", "Granger", "PCMCI", "cLSTM"]

    lines = []
    lines.append("% Auto-generated by generate_tables.py")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{Wall-clock runtime (seconds) for causal graph recovery.}")
    lines.append("\\label{tab:efficiency}")
    lines.append("\\begin{tabular}{l" + "c" * len(methods) + "}")
    lines.append("\\toprule")
    lines.append("Config & " + " & ".join(methods) + " \\\\")
    lines.append("\\midrule")

    for section in ["scaling_K", "scaling_T"]:
        if section not in results:
            continue
        for config, row in results[section].items():
            vals = []
            for m in methods:
                v = row.get(m)
                if v is not None:
                    vals.append(f"{v:.1f}")
                else:
                    vals.append("--")
            lines.append(f"{config} & " + " & ".join(vals) + " \\\\")

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")

    output_path = os.path.join(OUTPUT_DIR, "table4_efficiency.tex")
    with open(output_path, "w") as f:
        f.write("\n".join(lines))
    print(f"  Table 4 -> {output_path}")


def generate_table5():
    """Table 5: Ablation study."""
    results = load_results("ablation", "ablation_results.json")
    if results is None:
        print("  [SKIP] Table 5 — no ablation results found")
        return

    lines = []
    lines.append("% Auto-generated by generate_tables.py")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{Ablation study on VAR(1) chain K=5. "
                  "AUROC for Jacobian and Weight-Projection variants.}")
    lines.append("\\label{tab:ablation}")
    lines.append("\\begin{tabular}{lcc}")
    lines.append("\\toprule")
    lines.append("Configuration & Jacobian AUROC & Weight-Proj AUROC \\\\")
    lines.append("\\midrule")

    for section_name, section_key in [
        ("Model size", "model_size"),
        ("State dim", "state_dim"),
        ("Layers", "n_layers"),
        ("Data length", "data_length"),
    ]:
        if section_key not in results:
            continue
        lines.append(f"\\multicolumn{{3}}{{l}}{{\\textit{{{section_name}}}}} \\\\")
        for config, vals in results[section_key].items():
            jac = vals.get("auroc_jac", 0)
            weight = vals.get("auroc_weight", 0)
            lines.append(f"\\quad {config} & {jac:.3f} & {weight:.3f} \\\\")

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")

    output_path = os.path.join(OUTPUT_DIR, "table5_ablation.tex")
    with open(output_path, "w") as f:
        f.write("\n".join(lines))
    print(f"  Table 5 -> {output_path}")


def generate_all():
    print("Generating LaTeX tables from results...")
    print(f"Results dir: {RESULTS_DIR}")
    print(f"Output dir: {OUTPUT_DIR}")
    print()

    # List available results
    if os.path.exists(RESULTS_DIR):
        subdirs = [d for d in os.listdir(RESULTS_DIR)
                    if os.path.isdir(os.path.join(RESULTS_DIR, d))]
        print(f"Available results: {subdirs}\n")
    else:
        print("No results directory found.\n")

    generate_table1()
    generate_table2()
    generate_table3()
    generate_table4()
    generate_table5()

    print("\nDone. Include in main.tex with:")
    print("  \\input{table1_synthetic}")
    print("  \\input{table2_nonstationary}")
    print("  \\input{table3_realworld}")
    print("  \\input{table4_efficiency}")
    print("  \\input{table5_ablation}")


if __name__ == "__main__":
    generate_all()
