"""Generate camera-ready follow-up tables without modifying submitted results."""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ssm_causal.statistics import paired_bootstrap_ci  # noqa: E402

RESULTS = ROOT / "results/reviewer_followup"
ORIGINAL = ROOT / "results/corrected_workshop/nonlinearity_confirmation.json"


def summarize(primary, optional):
    """Join by data seed, never treating neural initializations as replicates."""
    expected = set(primary["protocol"]["data_seeds"])
    if primary["status"] != "complete" or optional["status"] != "complete":
        raise ValueError("Both follow-up stages must be complete")
    rows = {r["data_seed"]: r for r in primary["replicates"]}
    extra = {r["data_seed"]: r for r in optional["replicates"]}
    if len(rows) != len(primary["replicates"]) or set(rows) != expected:
        raise ValueError("Missing or duplicate primary data seeds")
    if len(extra) != len(optional["replicates"]) or set(extra) != expected | {0}:
        raise ValueError("Missing or duplicate optional data seeds")
    methods = tuple(rows[min(expected)]["methods"]) + ("DYNOTEARS", "VAR-LiNGAM")
    samples = {method: {metric: [] for metric in ("auroc", "auprc")} for method in methods}
    for seed in sorted(expected):
        if rows[seed]["input_sha256"] != extra[seed]["input_sha256"]:
            raise ValueError(f"Input mismatch for seed {seed}")
        for method in methods:
            result = (rows[seed] if method in rows[seed]["methods"] else extra[seed])["methods"][
                method
            ]
            if result.get("status", "ok") != "ok":
                raise ValueError(f"Failed method {method}, seed {seed}")
            for metric in ("auroc", "auprc"):
                samples[method][metric].append(result[metric])
    summary = {}
    reference = samples["Lagged-Bottleneck"]["auroc"]
    for method in methods:
        summary[method] = {}
        for metric in ("auroc", "auprc", "delta_auroc"):
            first = samples[method]["auroc" if metric == "delta_auroc" else metric]
            second = reference if metric == "delta_auroc" else np.zeros(len(first))
            ci = paired_bootstrap_ci(first, second, n_resamples=10000, seed=82000)
            summary[method][metric] = {"mean": ci.effect, "low": ci.ci_low, "high": ci.ci_high}
    return summary


def main():
    inputs = [
        RESULTS / "trajectory_replication.json",
        RESULTS / "optional_baselines.json",
        RESULTS / "lasso_diagnostic.json",
        ORIGINAL,
    ]
    primary, optional, diagnostic, nonlinearity = [json.loads(p.read_text()) for p in inputs]
    summary = summarize(primary, optional)
    lines = [
        "% Generated by paper/generate_reviewer_results.py; do not edit.",
        r"\newcommand{\TrajectoryTableRows}{%",
    ]
    for method, metrics in summary.items():
        cells = []
        for metric in ("auroc", "auprc", "delta_auroc"):
            c = metrics[metric]
            cells.append(f"${c['mean']:.3f}\\ [{c['low']:.3f},{c['high']:.3f}]$")
        if method == "Lagged-Bottleneck":
            cells[-1] = "---"
        lines.append(
            method.replace("Lagged-Bottleneck", "Lagged-BN") + " & " + " & ".join(cells) + r" \\"
        )
    lines += ["}", r"\newcommand{\NonlinearityGateRows}{%"]
    for c in nonlinearity["aggregates"]:
        ci = c["paired_effects"]["flat_lag_auroc_bootstrap_ci"]
        means = c["means"]
        failed = c["gate"]["failed_criteria"]
        adjusted = c["inference"]["holm_adjusted_p_value"]
        p_text = "---" if adjusted is None else f"{adjusted:.4f}"
        label = (
            "pass"
            if not failed
            else ",".join(
                {
                    "mean_flat_auroc_delta": "effect",
                    "bootstrap_lower_ci": "CI",
                    "holm_adjusted_p_value": "$p$",
                    "flat_auprc_superiority": "PR",
                    "flat_auprc_above_edge_prevalence": "prev",
                    "prediction_mse_margin": "MSE",
                }[f]
                for f in failed
            )
        )
        lines.append(
            f"{c['K']} & {c['T']} & {c['nonlinearity_mix']:g} & "
            f"{c['paired_effects']['flat_lag_auroc']:.2f} & "
            f"[{ci['low']:.2f},{ci['high']:.2f}] & "
            f"{p_text} & "
            f"{means['flat_lag_auprc']['Linear-BN']:.3f}/{means['flat_lag_auprc']['Lasso']:.3f} & "
            f"{means['prediction_mse']['Linear-BN'] / means['prediction_mse']['Lasso']:.3f} & "
            + label
            + r" \\"
        )
    lines += ["}"]
    original_optional = next(r for r in optional["replicates"] if r["data_seed"] == 0)
    for method, macro in [("DYNOTEARS", "DynotearsOriginal"), ("VAR-LiNGAM", "LingamOriginal")]:
        result = original_optional["methods"][method]
        if result["status"] != "ok":
            raise ValueError(f"Original seed baseline failed: {method}")
        lines.append("\\newcommand{\\" + macro + "}{" + f"{result['auroc']:.3f}" + "}")
    # Fail the build if the diagnostic no longer supports the camera-ready prose.
    diagnosed = diagnostic["replicates"]
    assert len(diagnosed) == 240 and len({r["replicate_id"] for r in diagnosed}) == 240
    zero = [r for r in diagnosed if r["K"] == 20 and r["T"] == 300]
    assert len(zero) == 60 and all(
        r["alpha"] == 1 and r["nonzero_off_diagonal_lag_scores"] == 0 for r in zero
    )
    large = [r for r in diagnosed if r["T"] == 600]
    assert len(large) == 120 and all(r["alpha"] == 0.1 and r["auroc"] == 1 for r in large)
    output = ROOT / "paper/draft/generated_reviewer_results.tex"
    output.write_text("\n".join(lines) + "\n")
    values = {
        "analysis": "post_review_exploratory",
        "bootstrap_resamples": 10000,
        "bootstrap_seed": 82000,
        "trajectory_summary": summary,
        "source_artifacts": {
            str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs
        },
    }
    (RESULTS / "paper_values.json").write_text(json.dumps(values, indent=2, allow_nan=False) + "\n")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
